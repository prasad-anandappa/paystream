-- PayStream schema. Written in portable SQL so the identical migrations run on
-- PostgreSQL 16 (local dev / production shape) and H2 in PostgreSQL mode (tests).
-- All money is stored as BIGINT minor units (cents). No floating point, ever.

CREATE TABLE accounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(120) NOT NULL,
    type           VARCHAR(32)  NOT NULL,
    currency       VARCHAR(3)   NOT NULL,
    balance_minor  BIGINT       NOT NULL DEFAULT 0,
    allow_negative BOOLEAN      NOT NULL DEFAULT FALSE,
    version        BIGINT       NOT NULL DEFAULT 0,
    created_at     TIMESTAMP    NOT NULL
);

CREATE TABLE journal_entries (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference   VARCHAR(120),
    description VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP    NOT NULL
);

CREATE TABLE postings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_entry_id BIGINT      NOT NULL REFERENCES journal_entries (id),
    account_id       BIGINT      NOT NULL REFERENCES accounts (id),
    direction        VARCHAR(8)  NOT NULL,
    amount_minor     BIGINT      NOT NULL,
    CONSTRAINT chk_posting_amount_positive CHECK (amount_minor > 0)
);

CREATE INDEX idx_postings_account ON postings (account_id);
CREATE INDEX idx_postings_entry ON postings (journal_entry_id);

CREATE TABLE transfers (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(120) NOT NULL,
    from_account_id BIGINT       NOT NULL REFERENCES accounts (id),
    to_account_id   BIGINT       NOT NULL REFERENCES accounts (id),
    amount_minor    BIGINT       NOT NULL,
    currency        VARCHAR(3)   NOT NULL,
    status          VARCHAR(32)  NOT NULL,
    journal_entry_id BIGINT      NOT NULL REFERENCES journal_entries (id),
    created_at      TIMESTAMP    NOT NULL,
    CONSTRAINT uq_transfers_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT chk_transfer_amount_positive CHECK (amount_minor > 0)
);

CREATE TABLE outbox_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(80)  NOT NULL,
    aggregate_id   VARCHAR(80)  NOT NULL,
    event_type     VARCHAR(120) NOT NULL,
    payload        TEXT         NOT NULL,
    status         VARCHAR(16)  NOT NULL,
    created_at     TIMESTAMP    NOT NULL,
    published_at   TIMESTAMP
);

CREATE INDEX idx_outbox_status ON outbox_events (status, created_at);

CREATE TABLE recon_reports (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    generated_at       TIMESTAMP NOT NULL,
    accounts_checked   INTEGER   NOT NULL,
    discrepancy_count  INTEGER   NOT NULL,
    total_debits_minor  BIGINT   NOT NULL,
    total_credits_minor BIGINT   NOT NULL,
    balanced           BOOLEAN   NOT NULL,
    details            TEXT      NOT NULL
);
